library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

entity alu_8bit_tb is
end alu_8bit_tb;

architecture Behavioral of alu_8bit_tb is

    component alu_8bit
        Port (
            A      : in  STD_LOGIC_VECTOR(7 downto 0);
            B      : in  STD_LOGIC_VECTOR(7 downto 0);
            OP     : in  STD_LOGIC_VECTOR(1 downto 0);
            RESULT : out STD_LOGIC_VECTOR(7 downto 0);
            COUT   : out STD_LOGIC
        );
    end component;

    signal A      : STD_LOGIC_VECTOR(7 downto 0) := (others => '0');
    signal B      : STD_LOGIC_VECTOR(7 downto 0) := (others => '0');
    signal OP     : STD_LOGIC_VECTOR(1 downto 0) := "00";
    signal RESULT : STD_LOGIC_VECTOR(7 downto 0);
    signal COUT   : STD_LOGIC;

begin

    UUT : alu_8bit
        port map (
            A      => A,
            B      => B,
            OP     => OP,
            RESULT => RESULT,
            COUT   => COUT
        );

    STIMULUS : process
    begin

        --------------------------------------------------
        -- Test 1: AND
        -- 10101010 AND 11001100 = 10001000
        --------------------------------------------------
        A  <= "10101010";
        B  <= "11001100";
        OP <= "00";
        wait for 100 ns;


        --------------------------------------------------
        -- Test 2: OR
        -- 10101010 OR 11001100 = 11101110
        --------------------------------------------------
        A  <= "10101010";
        B  <= "11001100";
        OP <= "01";
        wait for 100 ns;


        --------------------------------------------------
        -- Test 3: XOR
        -- 10101010 XOR 11001100 = 01100110
        --------------------------------------------------
        A  <= "10101010";
        B  <= "11001100";
        OP <= "10";
        wait for 100 ns;


        --------------------------------------------------
        -- Test 4: ADD
        -- 5 + 3 = 8
        --------------------------------------------------
        A  <= "00000101";
        B  <= "00000011";
        OP <= "11";
        wait for 100 ns;


        --------------------------------------------------
        -- Test 5: ADD
        -- 100 + 50 = 150
        --------------------------------------------------
        A  <= "01100100";
        B  <= "00110010";
        OP <= "11";
        wait for 100 ns;


        --------------------------------------------------
        -- Test 6: ADD with Carry
        -- 255 + 1 = 256
        -- RESULT = 00000000
        -- COUT   = 1
        --------------------------------------------------
        A  <= "11111111";
        B  <= "00000001";
        OP <= "11";
        wait for 100 ns;


        --------------------------------------------------
        -- Test 7: AND
        -- 11110000 AND 00001111 = 00000000
        --------------------------------------------------
        A  <= "11110000";
        B  <= "00001111";
        OP <= "00";
        wait for 100 ns;


        --------------------------------------------------
        -- Test 8: OR
        -- 11110000 OR 00001111 = 11111111
        --------------------------------------------------
        A  <= "11110000";
        B  <= "00001111";
        OP <= "01";
        wait for 100 ns;


        --------------------------------------------------
        -- Test 9: XOR
        -- 11111111 XOR 11111111 = 00000000
        --------------------------------------------------
        A  <= "11111111";
        B  <= "11111111";
        OP <= "10";
        wait for 100 ns;


        wait;

    end process;

end Behavioral;